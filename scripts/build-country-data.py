#!/usr/bin/env python3
"""Dev tool: convert world-atlas countries-110m.json (TopoJSON) into a compact Python module.

usage: python3 -I scripts/build-country-data.py <path/to/countries-110m.json>

Source: world-atlas 2.0.2 (ISC, Copyright 2013-2019 Michael Bostock), a redistribution of
Natural Earth 1:110m Admin 0 boundaries (public domain). Not run at app runtime.
"""
import json
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[1] / "engine/src/organize_gui/classify/countries_data.py"


def main(source):
    topology = json.loads(Path(source).read_text())
    (sx, sy), (tx, ty) = topology["transform"]["scale"], topology["transform"]["translate"]
    arcs = []
    for arc in topology["arcs"]:
        x = y = 0
        points = []
        for dx, dy in arc:
            x += dx
            y += dy
            points.append((round(x * sx + tx, 2), round(y * sy + ty, 2)))
        arcs.append(points)

    def ring(indexes):
        points = []
        for index in indexes:
            segment = arcs[index] if index >= 0 else list(reversed(arcs[~index]))
            points.extend(segment[1:] if points else segment)
        return [value for point in points for value in point]

    countries = []
    for geometry in topology["objects"]["countries"]["geometries"]:
        name = geometry.get("properties", {}).get("name")
        if not name or geometry.get("type") not in ("Polygon", "MultiPolygon"):
            continue
        polygons = geometry["arcs"] if geometry["type"] == "MultiPolygon" else [geometry["arcs"]]
        rings = [ring(indexes) for polygon in polygons for indexes in polygon]
        xs = [value for item in rings for value in item[0::2]]
        ys = [value for item in rings for value in item[1::2]]
        countries.append((name, (min(xs), min(ys), max(xs), max(ys)), rings))
    countries.sort()
    lines = [
        '"""Generated by scripts/build-country-data.py. Do not edit.',
        "",
        "Coarse country outlines (lon, lat pairs) from world-atlas 2.0.2 countries-110m.json",
        "(ISC, Copyright 2013-2019 Michael Bostock), derived from Natural Earth 1:110m",
        'Admin 0 boundaries (public domain). Used offline only, to name photo trips."""',
        "",
        "COUNTRIES = [",
    ]
    for name, bbox, rings in countries:
        lines.append("    (%r, %r, %r)," % (name, bbox, rings))
    lines.append("]")
    OUTPUT.write_text("\n".join(lines) + "\n")
    print("%d countries -> %s (%d bytes)" % (len(countries), OUTPUT, OUTPUT.stat().st_size))


if __name__ == "__main__":
    main(sys.argv[1])
